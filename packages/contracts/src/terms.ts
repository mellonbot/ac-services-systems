import type { Tier } from "./tiers.ts";

/**
 * THE TERM POLICY REGISTER — D2 part two.
 *
 * The master plan's sentence "terms flow downward and may be overridden at any
 * level" is five rules wearing one coat (claude/07_D2_Hierarchy_Findings.md).
 * A resolver built to that sentence returns confidently wrong answers with a
 * clean trace: a location sets its own payment terms and the consolidated
 * invoice becomes unpayable; a location relaxes an SLA we carry the whole
 * exposure on; a site inherits the vendor warranty attached to the site next
 * door.
 *
 * So a term carries a POLICY, not just a value, and the policy is two
 * orthogonal axes — not four enum values, because an enum bundles independent
 * properties and the fifth case needs a fifth branch in every consumer:
 *
 *   authoring   which tiers may hold an override row for this term
 *   combine     how competing values resolve down the path
 *                 nearest   most specific tier wins
 *                 ratchet   an override may only TIGHTEN, direction declared
 *                 attach    binds to exactly one node and never walks
 *
 * What is NOT an axis: what happens on violation. It is always RAISE, on every
 * term, in every direction. Making it configurable is how an override flag
 * re-enters the system wearing a different name.
 *
 * THIS REGISTER IS CODE, NOT A TABLE. A table an ops user can edit is a table
 * someone edits at T-4 so tonight's invoice runs. It IS mirrored into the
 * database (`term_registry`, generated by tools/ci/emit-schema.ts, SELECT-only
 * for every runtime role) so that the admission trigger in migrations/0002 can
 * refuse an illegal override row from a psql session — but the mirror is
 * regenerated from here, never edited.
 *
 * Asymmetry to know before signing contracts: adding a term is cheap. Changing
 * a term's policy after override rows exist is not — every row written under
 * the old policy has to be re-admitted, and the ones that fail are terms a
 * customer currently believes they have.
 */

export type Combine =
  | { readonly kind: "nearest" }
  | { readonly kind: "ratchet"; readonly stricter: "lower" | "higher" }
  | { readonly kind: "attach" };

export type ValueKind = "int" | "money" | "text" | "enum" | "bool";

export type TermPolicy = {
  readonly key: string;
  readonly authoring: readonly Tier[];
  readonly combine: Combine;
  readonly valueKind: ValueKind;
  /** Allowed values when valueKind is "enum". Order is the ordinal used by ratchet: index 0 is LOWEST. */
  readonly values?: readonly string[];
  /** Why this term has this policy — the failure it prevents. Read by the S2 refusal message. */
  readonly rationale: string;
  /** Default when nothing on the path sets it. `undefined` means resolution raises. */
  readonly fallback?: unknown;
};

