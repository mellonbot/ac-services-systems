export const TERM_KEYS = Object.freeze(Object.keys(TERMS)) as readonly string[];

export class UnknownTermError extends Error {
  constructor(key: string) {
    super(`[terms] "${key}" is not in the term policy register. A term with no entry raises rather than defaulting to cascade — add it to packages/contracts/src/terms.ts in a reviewed diff, stating its authoring tiers and combine rule.`);
    this.name = "UnknownTermError";
  }
}

export const termPolicy = (key: string): TermPolicy => {
  const p = TERMS[key];
  if (!p) throw new UnknownTermError(key);
  return p;
};

/** Ordinal rank used by ratchet. Ints compare numerically; enums by declared order. */
export const termRank = (p: TermPolicy, value: unknown): number => {
  if (p.valueKind === "enum") {
    const i = (p.values ?? []).indexOf(String(value));
    if (i < 0) throw new Error(`[terms] "${value}" is not a legal value for ${p.key}; legal: ${(p.values ?? []).join(", ")}`);
    return i;
  }
  if (p.valueKind === "int") {
    if (typeof value !== "number" || !Number.isInteger(value)) throw new Error(`[terms] ${p.key} must be an integer, got ${JSON.stringify(value)}`);
    return value;
  }
  throw new Error(`[terms] ${p.key} is ${p.valueKind}; ratchet needs an ordinal`);
};

/** Shape check for a value against its term. Throws with the reason; never coerces. */
export const checkTermValue = (p: TermPolicy, value: unknown): void => {
  switch (p.valueKind) {
    case "int":
      if (typeof value !== "number" || !Number.isInteger(value)) throw new Error(`[terms] ${p.key} must be an integer`);
      return;
    case "bool":
      if (typeof value !== "boolean") throw new Error(`[terms] ${p.key} must be true or false`);
      return;
    case "text":
      if (typeof value !== "string" || value.length === 0) throw new Error(`[terms] ${p.key} must be non-empty text`);
      return;
    case "enum":
      termRank(p, value);
      return;
    case "money":
      // Money crosses the jsonb boundary as a string of minor units. A JSON number is IEEE754.
      if (typeof value !== "string" || !/^-?\d+$/.test(value)) throw new Error(`[terms] ${p.key} is money: a string of integer minor units, not a number`);
      return;
  }
};
