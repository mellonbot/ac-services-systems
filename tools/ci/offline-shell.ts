import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { SURFACE_PATHS, type SurfaceId } from "../../packages/contracts/src/index.ts";

/**
 * `/sw.js` — THE OFFLINE SHELL. A technician who opens the tablet with no
 * signal must still get a page: S1 to send them on, S5 to open the shift
 * their tab holds (packages/shell `heldShift`). Nothing else on the site works
 * offline, so nothing else is kept.
 *
 * What it does, all of it:
 *   - keeps every built file of S1 and S5 — and only those — in one cache
 *     named for their contents, so each deploy is a new cache and the last is
 *     dropped when the new worker takes over;
 *   - answers those files, and a navigation to `/` or under `/technician/`,
 *     from the network first and from the cache only when the network fails,
 *     so a deploy still reaches a device the moment it is online;
 *   - touches nothing else: no other surface's path, no other origin (the
 *     gateway is one), no request but a GET.
 *
 * A page is kept under its directory URL (`/`, `/technician/`), never as
 * `index.html`: Pages redirects that name, and a navigation answered with a
 * redirected response is a network error.
 */
export const OFFLINE_SURFACES = ["S1", "S5"] as const satisfies readonly SurfaceId[];

const prefixOf = (id: SurfaceId): string => (SURFACE_PATHS[id] === "/" ? "" : SURFACE_PATHS[id]);

/** The URL of every file a built surface serves, as the site serves it. Source maps are never published. */
export const builtUrls = (id: SurfaceId, outDir: string): { url: string; file: string }[] => {
  const walk = (dir: string): string[] => readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
  return walk(outDir)
    .filter((file) => !file.endsWith(".map"))
    .map((file) => {
      const rel = relative(outDir, file).split(sep).join("/");
      return { url: `${prefixOf(id)}/${rel === "index.html" ? "" : rel}`, file };
    })
    .sort((a, b) => a.url.localeCompare(b.url));
};

export const serviceWorker = (files: readonly { url: string; file: string }[]): string => {
  const hash = createHash("sha256");
  for (const f of files) hash.update(f.url).update("\0").update(readFileSync(f.file)).update("\0");
  const cache = `ac-offline-${hash.digest("hex").slice(0, 16)}`;
  const urls = files.map((f) => f.url);
  const s5 = SURFACE_PATHS.S5;
  return `// GENERATED by tools/ci/offline-shell.ts. Do not edit.
const CACHE = ${JSON.stringify(cache)};
const FILES = ${JSON.stringify(urls)};
const PAGES = FILES.filter((u) => u.endsWith("/"));

self.addEventListener("install", (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await c.addAll(FILES.filter((u) => !u.endsWith("/")));
    for (const page of PAGES) {
      const res = await fetch(page, { cache: "no-cache" });
      if (!res.ok) throw new Error(page + " answered " + res.status);
      await c.put(page, new Response(await res.blob(), { status: 200, headers: res.headers }));
    }
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith("ac-offline-") && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

const keyFor = (req) => {
  if (req.method !== "GET") return null;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return null;
  if (req.mode === "navigate") {
    if (url.pathname === ${JSON.stringify(s5)} || url.pathname.startsWith(${JSON.stringify(`${s5}/`)})) return ${JSON.stringify(`${s5}/`)};
    return url.pathname === "/" ? "/" : null;
  }
  return FILES.includes(url.pathname) && !url.pathname.endsWith("/") ? url.pathname : null;
};

self.addEventListener("fetch", (e) => {
  const key = keyFor(e.request);
  if (!key) return;
  e.respondWith(fetch(e.request).catch(async () => (await caches.match(key, { cacheName: CACHE })) ?? Response.error()));
});
`;
};
